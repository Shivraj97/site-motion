// style export: the project's look (style pack + brand tokens) in the formats a site's own code already speaks,
// so buttons, cards and transitions match the animations, not just the colours.
//   css        :root custom properties + .sm-label / .sm-motif / .sm-texture classes
//   tailwind   a Tailwind v4 @theme block (overrides --shadow-sm/md/lg, --radius-*, --ease-*, colours, fonts) + @utility
//   dtcg       W3C Design Tokens (DTCG 2025.10) JSON: color, dimension, shadow, cubicBezier, duration, typography
//   design-md  a "Motion and illustration" section for DESIGN.md, so coding agents keep new UI in the look
// Every format comes from one resolved model (lookModel), so they always agree with each other and with the scenes.
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const S = require("../runtime/style.cjs");

export const FORMATS = ["css", "tailwind", "dtcg", "design-md"];
// component transitions (not scene timing): a sensible base, scaled by the pack's tempo
const DURATIONS = { fast: 160, base: 240, slow: 400 };
const MARK_START = "<!-- site-motion:start -->";
const MARK_END = "<!-- site-motion:end -->";

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
// "soft-ui" → "Soft UI"; a code or "custom" stays as it is
export const titleOf = (name) => (/^sm1\./.test(name) || name === "custom" ? name : name.split("-").map((w) => (w === "ui" ? "UI" : w[0].toUpperCase() + w.slice(1))).join(" "));
const round = (n, d = 2) => Math.round(n * 10 ** d) / 10 ** d;
const bez = (b) => `cubic-bezier(${b.join(", ")})`;

// "rgba(18,20,17,0.18)" | "#121411" → { r, g, b, a }
function parseColor(c) {
  const m = /^rgba?\(([^)]+)\)$/.exec(c.trim());
  if (m) { const [r, g, b, a = 1] = m[1].split(",").map(Number); return { r, g, b, a }; }
  const h = c.replace("#", "");
  const v = h.length === 3 ? h.split("").map((x) => x + x).join("") : h.slice(0, 6);
  return { r: parseInt(v.slice(0, 2), 16), g: parseInt(v.slice(2, 4), 16), b: parseInt(v.slice(4, 6), 16), a: 1 };
}
const isDark = (c) => { const { r, g, b } = parseColor(c); return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255 < 0.2; };
const hexOf = ({ r, g, b }) => "#" + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

// the shadow strings style.cjs emits ("0 12px 32px -18px rgba(…)", rings, tinted offsets) → layers; "no shadow" → []
export function shadowLayers(css) {
  return css.split(/,(?![^(]*\))/).map((layer) => {
    const m = /^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(.+)$/.exec(layer.trim());
    if (!m || m[5].trim() === "transparent") return null;
    return { x: +m[1], y: +m[2], blur: +m[3], spread: +m[4], color: parseColor(m[5]) };
  }).filter(Boolean);
}

// label fonts in style.cjs are CSS vars a scene page defines; outside a scene they become the brand's own stacks
function fontStack(value, tokens) {
  if (value.includes("--font-mono")) return tokens.font.mono;
  if (value.includes("--font-sans")) return tokens.font.sans;
  if (value.includes("--font-display")) return tokens.font.display || "Georgia, 'Times New Roman', serif";
  return value;
}

/** Everything every format needs, resolved for these tokens. pack: a normalized pack (not native). */
export function lookModel(pack, tokens) {
  if (!pack) throw new Error(`"native" means each scene keeps its own look, so there is no shared look to export. Pick one first: site-motion style set ink (or pass --style)`);
  const r = S.resolve(pack, tokens);
  const coloured = S.applyColorMode(tokens, pack.colorMode);
  const tempo = r.tempo;
  return {
    name: titleOf(pack.name), code: r.code, pack, brand: tokens.name || "custom",
    color: { ...tokens.color }, palette: [...coloured.palette],
    font: { sans: tokens.font.sans, mono: tokens.font.mono, ...(tokens.font.display ? { display: tokens.font.display } : {}) },
    stroke: { hair: r.stroke.hair, fine: r.stroke.fine, regular: r.stroke.regular, bold: r.stroke.bold, color: r.stroke.colorValue },
    shadow: r.shadow, // [level0 … level3] as CSS
    radius: r.radius, cornerK: r.cornerK,
    glow: r.glow ? r.glow.css : null,
    label: { font: fontStack(r.label.font, tokens), transform: r.label.transform, tracking: r.label.tracking, style: r.label.style },
    type: { weight: r.type.weight, tracking: r.type.tracking, k: r.typeK },
    ease: { ...S.STUDIO_EASE, ...(r.ease || {}) },
    duration: Object.fromEntries(Object.entries(DURATIONS).map(([k, ms]) => [k, Math.round(ms * tempo)])),
    tempo, stagger: r.stagger,
    texture: pack.texture === "none" ? null : { kind: pack.texture, amount: r.texture.amount, image: S.textureImage(pack.texture, tokens), dark: isDark(tokens.color.paper) },
    motif: pack.motif === "none" ? null : { kind: pack.motif, image: S.motifImage(pack.motif, tokens) },
  };
}

const header = (m, how) => `site-motion look: ${m.name} (${m.code}) on ${m.brand}. Generated by \`site-motion style export --format ${how}\`; re-run it after \`style set\` instead of editing by hand.`;
const textureOpacity = (t) => round(t.amount * (t.kind === "grain" || t.kind === "paper" ? 2.5 : 1.2), 3);
// background-image values from style.cjs are either a url() or a gradient with its size appended ("… 0 0 / 6px 6px")
const bgDecls = (image) => {
  const b = S.bgStyle(image);
  return b.backgroundSize ? `background-image: ${b.backgroundImage}; background-position: ${b.backgroundPosition}; background-size: ${b.backgroundSize};` : `background-image: ${image}; background-size: cover;`;
};

function classes(m, sel = (n) => `.${n}`) {
  const out = [];
  out.push(`${sel("sm-label")} {\n  font-family: ${m.label.font};\n  font-size: 12px;\n  font-style: ${m.label.style};\n  text-transform: ${m.label.transform};\n  letter-spacing: ${m.label.tracking};\n}`);
  if (m.motif) out.push(`/* the look's recurring background: put it behind illustrations and hero panels */\n${sel("sm-motif")} {\n  ${bgDecls(m.motif.image).replace(/; /g, ";\n  ")}\n}`);
  if (m.texture) out.push(`/* the look's texture: a static overlay, never animated */\n${sel("sm-texture")} {\n  position: relative;\n  isolation: isolate;\n  &::after {\n    content: "";\n    position: absolute;\n    inset: 0;\n    pointer-events: none;\n    opacity: ${textureOpacity(m.texture)};\n    mix-blend-mode: ${m.texture.dark ? "screen" : "multiply"};\n    ${bgDecls(m.texture.image).replace(/; /g, ";\n    ")}\n  }\n}`);
  return out.join("\n\n");
}

function varsBlock(m) {
  const v = [];
  for (const [k, c] of Object.entries(m.color)) v.push(`--sm-color-${kebab(k)}: ${c};`);
  m.palette.forEach((c, i) => v.push(`--sm-palette-${i + 1}: ${c};`));
  for (const [k, f] of Object.entries(m.font)) v.push(`--sm-font-${k}: ${f};`);
  for (const k of ["hair", "fine", "regular", "bold"]) v.push(`--sm-stroke-${k}: ${m.stroke[k]}px;`);
  v.push(`--sm-stroke-color: ${m.stroke.color};`);
  m.shadow.forEach((s, i) => v.push(`--sm-shadow-${i}: ${s};`));
  for (const [k, px] of Object.entries(m.radius)) v.push(`--sm-radius-${k}: ${px}px;`);
  v.push(`--sm-glow: ${m.glow || "0 0 0 0 transparent"};`);
  for (const [k, b] of Object.entries(m.ease)) v.push(`--sm-ease-${kebab(k)}: ${bez(b)};`);
  for (const [k, ms] of Object.entries(m.duration)) v.push(`--sm-duration-${k}: ${ms}ms;`);
  v.push(`--sm-stagger: ${m.stagger};`);
  v.push(`--sm-type-weight: ${m.type.weight};`);
  if (m.type.tracking) v.push(`--sm-type-tracking: ${m.type.tracking};`);
  return v;
}

export function toCss(m) {
  return `/* ${header(m, "css")}\n   Shadows: --sm-shadow-1 (resting) … --sm-shadow-3 (in focus). Transitions: var(--sm-duration-base) var(--sm-ease-signature). */\n:root {\n  ${varsBlock(m).join("\n  ")}\n}\n\n${classes(m)}\n`;
}

export function toTailwind(m) {
  const none = "0 0 #0000"; // Tailwind's own "no shadow"
  const sh = (i) => (shadowLayers(m.shadow[i]).length ? m.shadow[i] : none);
  const t = [];
  for (const [k, c] of Object.entries(m.color)) t.push(`--color-${kebab(k)}: ${c};`);
  m.palette.forEach((c, i) => t.push(`--color-palette-${i + 1}: ${c};`));
  t.push(`--font-sans: ${m.font.sans};`, `--font-mono: ${m.font.mono};`);
  if (m.font.display) t.push(`--font-display: ${m.font.display};`);
  for (const [k, px] of Object.entries(m.radius)) t.push(`--radius-${k}: ${px}px;`);
  t.push(`--shadow-sm: ${sh(1)};`, `--shadow-md: ${sh(2)};`, `--shadow-lg: ${sh(3)};`);
  if (m.glow) t.push(`--shadow-glow: ${m.glow};`);
  t.push(`--ease-signature: ${bez(m.ease.signature)};`, `--ease-snappy: ${bez(m.ease.snappy)};`, `--ease-soft: ${bez(m.ease.soft)};`, `--ease-in-out: ${bez(m.ease.inOut)};`);
  t.push(`--default-transition-duration: ${m.duration.base}ms;`, `--default-transition-timing-function: ${bez(m.ease.signature)};`);
  // the rest has no Tailwind namespace: plain variables, used as border-[length:var(--sm-stroke-fine)] etc.
  const plain = [
    ...["hair", "fine", "regular", "bold"].map((k) => `--sm-stroke-${k}: ${m.stroke[k]}px;`), `--sm-stroke-color: ${m.stroke.color};`,
    ...Object.entries(m.duration).map(([k, ms]) => `--sm-duration-${k}: ${ms}ms;`), `--sm-stagger: ${m.stagger};`,
    `--sm-type-weight: ${m.type.weight};`, ...(m.type.tracking ? [`--sm-type-tracking: ${m.type.tracking};`] : []),
  ];
  const utils = classes(m, (n) => `@utility ${n}`);
  return `/* ${header(m, "tailwind")}\n   Tailwind v4: paste after @import "tailwindcss". shadow-sm/md/lg, rounded-sm/md/lg, ease-*, the default transition and the
   brand colours now match the scenes; sm-label, sm-motif and sm-texture are utilities. */\n@theme {\n  ${t.join("\n  ")}\n}\n\n:root {\n  ${plain.join("\n  ")}\n}\n\n${utils}\n`;
}

// ---------- DTCG 2025.10 ----------
const dColor = (c) => { const p = parseColor(c); return { colorSpace: "srgb", components: [p.r, p.g, p.b].map((v) => round(v / 255, 4)), ...(p.a < 1 ? { alpha: round(p.a, 3) } : {}), hex: hexOf(p) }; };
const dim = (px) => ({ value: round(px, 3), unit: "px" });
const tok = ($type, $value, $description) => ({ $type, $value, ...($description ? { $description } : {}) });
const dShadow = (css) => shadowLayers(css).map((l) => ({ color: dColor(l.color.a < 1 ? `rgba(${l.color.r},${l.color.g},${l.color.b},${l.color.a})` : hexOf(l.color)), offsetX: dim(l.x), offsetY: dim(l.y), blur: dim(l.blur), spread: dim(l.spread) }));
const families = (stack) => stack.split(",").map((f) => f.trim().replace(/^['"]|['"]$/g, "")).filter(Boolean);
const emPx = (em, size) => (em && em !== "0" ? round(parseFloat(em) * size, 3) : 0);

export function toDtcg(m) {
  const NONE = [{ color: dColor("rgba(0,0,0,0)"), offsetX: dim(0), offsetY: dim(0), blur: dim(0), spread: dim(0) }];
  const out = {
    $description: header(m, "dtcg"),
    color: Object.fromEntries(Object.entries(m.color).map(([k, c]) => [k, tok("color", dColor(c))])),
    palette: Object.fromEntries(m.palette.map((c, i) => [String(i + 1), tok("color", dColor(c), "a category colour, in the look's colour mode (" + m.pack.colorMode + ")")])),
    font: Object.fromEntries(Object.entries(m.font).map(([k, f]) => [k, tok("fontFamily", families(f))])),
    stroke: { ...Object.fromEntries(["hair", "fine", "regular", "bold"].map((k) => [k, tok("dimension", dim(m.stroke[k]))])), color: tok("color", dColor(m.stroke.color)) },
    radius: Object.fromEntries(Object.entries(m.radius).map(([k, px]) => [k, tok("dimension", dim(px))])),
    shadow: Object.fromEntries([1, 2, 3].map((i) => { const l = dShadow(m.shadow[i]); return [String(i), tok("shadow", l.length ? l : NONE, ["resting", "raised", "in focus"][i - 1])]; })),
    ...(m.glow ? { glow: tok("shadow", dShadow(m.glow)) } : {}),
    easing: Object.fromEntries(Object.entries(m.ease).map(([k, b]) => [k, tok("cubicBezier", b)])),
    duration: Object.fromEntries(Object.entries(m.duration).map(([k, ms]) => [k, tok("duration", { value: ms, unit: "ms" })])),
    typography: {
      label: tok("typography", { fontFamily: families(m.label.font), fontSize: dim(12), fontWeight: 400, letterSpacing: dim(emPx(m.label.tracking, 12)), lineHeight: 1.4 }, `${m.label.transform === "uppercase" ? "uppercase" : "sentence case"}${m.label.style === "italic" ? ", italic" : ""}`),
      headline: tok("typography", { fontFamily: families(m.font.display || m.font.sans), fontSize: dim(56), fontWeight: m.type.weight, letterSpacing: dim(emPx(m.type.tracking || "-0.02em", 56)), lineHeight: 1.05 }),
    },
    $extensions: { "dev.site-motion": { code: m.code, pack: Object.fromEntries(Object.keys(S.KNOBS).map((k) => [k, m.pack[k]])), stagger: m.stagger, tempo: m.tempo } },
  };
  return JSON.stringify(out, null, 2) + "\n";
}

