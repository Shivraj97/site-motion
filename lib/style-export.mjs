export function exportStyle(pack, tokens, format) {
  const m = lookModel(pack, tokens);
  if (format === "css") return toCss(m);
  if (format === "tailwind") return toTailwind(m);
  if (format === "dtcg" || format === "json") return toDtcg(m);
  if (format === "design-md" || format === "md") return toDesignMd(m);
  throw new Error(`unknown export format "${format}" (formats: ${FORMATS.join(", ")})`);
}

// DESIGN.md is the user's file: replace only our marked section, or append it once
export function mergeDesignMd(existing, section) {
  if (!existing) return `# Design\n\n${section}`;
  const a = existing.indexOf(MARK_START), b = existing.indexOf(MARK_END);
  if (a !== -1 && b > a) return existing.slice(0, a) + section.trimEnd() + existing.slice(b + MARK_END.length);
  return existing.replace(/\s*$/, "\n\n") + section;
}
